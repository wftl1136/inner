/** Счётчик непрочитанного: 1–99, дальше 99+ */
export function Badge({ n, className = '' }: { n: number; className?: string }) {
  if (n <= 0) return null;
  return <span className={'badge ' + className}>{n > 99 ? '99+' : n}</span>;
}

